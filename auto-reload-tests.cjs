const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const storage=new Map();
let reloads=0,blockedStorage=false;
const ctx={window:{},Date,localStorage:{getItem:k=>storage.get(k)||null,setItem(k,v){if(blockedStorage)throw Error('Storage unavailable');storage.set(k,v);}},location:{reload(){
  assert.equal(JSON.parse(storage.get('af-trainer-one-shot-v1')).pending.kind,'resource','Plan must be saved before reload');
  reloads++;
}}};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname+'/test-lab.js','utf8'),ctx);
ctx.lab=ctx.window.__autoForgeTestLabFactory(()=>{});
const source=fs.readFileSync(__dirname+'/inspector.js','utf8');
vm.runInContext(source.slice(source.indexOf('  function applyChange('),source.indexOf('  function render(')),ctx);
const state={forge:{level:5},core:{last:320},player:{ingame_time:1000},inventory:{items:{arena_currency:8}}};
ctx.applyChange('resource',{resource:'arena_currency',amount:1});
assert.equal(reloads,0,'Unidentified account must not reload');
const id=ctx.lab.identity('reload-fixture');ctx.lab.bind(id);ctx.lab.observe(state);
ctx.applyChange('resource',{resource:'arena_currency',amount:1});
assert.equal(reloads,1);
ctx.applyChange('resource',{resource:'arena_currency',amount:-1});
assert.equal(reloads,1,'Invalid apply must not reload even with an older pending plan');
const next=ctx.window.__autoForgeTestLabFactory(()=>{});
const body=JSON.stringify({status:0,time:1800000000,data:{data:state}});
assert.equal(JSON.parse(next.transform(body,id)).data.data.inventory.items.arena_currency,9,'Reloaded instance applies the saved plan');
assert.equal(JSON.parse(next.transform(body,id)).data.data.inventory.items.arena_currency,9,'Recovery keeps the prior result without applying the increment twice');
blockedStorage=true;
ctx.applyChange('resource',{resource:'arena_currency',amount:1});
assert.match(ctx.lab.summary().message,/storage/i);
assert.equal(reloads,1,'Storage failure must not reload');
assert.equal((source.match(/lab\?\.arm\(/g)||[]).length,1);
assert.equal((source.match(/lab\.arm\(/g)||[]).length,0,'All saved-state UI controls use automatic reload');
console.log('PASS: persist before reload, validation and storage failure guards, pending-plan rejection, reload consumption and one-shot behavior');
